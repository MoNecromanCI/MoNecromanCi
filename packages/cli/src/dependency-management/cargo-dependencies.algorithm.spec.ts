import { cargoDependencies, cargoLockVersion, replaceCargoSpec } from './cargo-dependencies.algorithm'

const MANIFEST = [
  '[package]',
  'name = "hello"',
  'version = "0.1.0"',
  'edition = "2021"',
  '',
  '[dependencies]',
  'serde = { version = "1.0", features = ["derive"] }',
  'itoa = "1"',
  '# a sibling crate in this workspace',
  'kit = { path = "../../libs/kit", version = "0.1.0" }',
  'shared = { workspace = true }',
  '',
  '[dev-dependencies]',
  'pretty_assertions = "1.4"',
  '',
  '[build-dependencies]',
  'cc = "1.0"',
  '',
].join('\n')

describe('cargoDependencies', () => {
  it('reads plain and inline-table versions from the three dependency tables, with their section', () => {
    expect(cargoDependencies(MANIFEST)).toEqual([
      { name: 'serde', spec: '1.0', section: 'dep', rewritable: true },
      { name: 'itoa', spec: '1', section: 'dep', rewritable: true },
      { name: 'kit', spec: '0.1.0', section: 'dep', rewritable: false },
      { name: 'pretty_assertions', spec: '1.4', section: 'devDep', rewritable: true },
      { name: 'cc', spec: '1.0', section: 'buildDep', rewritable: true },
    ])
  })

  it('does not read the package table, a workspace dependency, or a comment', () => {
    const names = cargoDependencies(MANIFEST).map(entry => entry.name)

    expect(names).not.toContain('name')
    expect(names).not.toContain('version')
    expect(names).not.toContain('shared')
  })

  it('reads CRLF text', () => {
    expect(cargoDependencies(MANIFEST.replaceAll('\n', '\r\n')).map(entry => entry.name)).toContain('itoa')
  })
})

describe('replaceCargoSpec', () => {
  it('changes a plain version and nothing else', () => {
    const next = replaceCargoSpec(MANIFEST, 'itoa', '2')

    expect(next).toContain('itoa = "2"')
    expect(next.replace('itoa = "2"', 'itoa = "1"')).toBe(MANIFEST)
  })

  it('changes only the version of an inline table and keeps its features', () => {
    expect(replaceCargoSpec(MANIFEST, 'serde', '1.1')).toContain('serde = { version = "1.1", features = ["derive"] }')
  })

  it('leaves the text alone for an undeclared crate and for a workspace dependency', () => {
    expect(replaceCargoSpec(MANIFEST, 'numpy', '1')).toBe(MANIFEST)
    expect(replaceCargoSpec(MANIFEST, 'shared', '1')).toBe(MANIFEST)
  })

  it('keeps CRLF line endings', () => {
    const crlf = MANIFEST.replaceAll('\n', '\r\n')

    expect(replaceCargoSpec(crlf, 'cc', '1.2')).toBe(crlf.replace('cc = "1.0"', 'cc = "1.2"'))
  })
})

describe('cargoLockVersion', () => {
  const LOCK = [
    '# This file is automatically @generated by Cargo.',
    'version = 3',
    '',
    '[[package]]',
    'name = "itoa"',
    'version = "1.0.9"',
    '',
    '[[package]]',
    'name = "syn"',
    'version = "1.0.109"',
    '',
    '[[package]]',
    'name = "syn"',
    'version = "2.0.48"',
    '',
  ].join('\n')

  it('answers the resolved version', () => {
    expect(cargoLockVersion(LOCK, 'itoa')).toBe('1.0.9')
  })

  it('answers the highest when a crate is present at two versions', () => {
    expect(cargoLockVersion(LOCK, 'syn')).toBe('2.0.48')
  })

  it('answers nothing for a crate the lockfile does not hold', () => {
    expect(cargoLockVersion(LOCK, 'serde')).toBeUndefined()
  })
})
